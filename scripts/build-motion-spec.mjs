// Checks tokens/motion-usage.json against the code and writes docs/MOTION.md,
// the engineer-facing motion spec. The check is what keeps the spec honest:
//   - every token and curve an entry names must exist,
//   - the file an entry points at must really use that token and curve,
//   - every component motion token must be documented at least once.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { flatten, resolve } from "./lib/tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const core = resolve(flatten(JSON.parse(read("tokens/core.json"))));
const usage = JSON.parse(read("tokens/motion-usage.json"));

const ms = (token) => parseFloat(core.get(token).$value);
const cssVar = (token) => `--rk-${token.replaceAll(".", "-")}`;
const curve = (name) => (name === "linear" ? "linear" : `cubic-bezier(${core.get(`motion.easing.${name}`).$value.join(", ")})`);

const errors = [];
const used = new Set();
const sources = new Map();
const source = (file) => sources.get(file) ?? sources.set(file, read(file)).get(file);

for (const component of usage.components) {
  for (const beat of component.beats) {
    const where = `${component.name} / ${beat.beat}`;
    const file = beat.file ?? component.file;
    const tokens = [beat.duration, beat.stagger, ...beat.delay.map(([t]) => t)].filter(Boolean);
    for (const t of tokens) {
      if (!core.has(t)) errors.push(`${where}: unknown token "${t}"`);
      used.add(t);
    }
    if (beat.easing !== "linear" && !core.has(`motion.easing.${beat.easing}`)) errors.push(`${where}: unknown curve "${beat.easing}"`);
    if (errors.length) continue;

    // Does the code really use what the spec claims? Delays are sequencing,
    // sometimes done in JavaScript, so only duration, stagger and curve are checked.
    const code = source(file);
    const isCss = file.endsWith(".css");
    for (const t of [beat.duration, beat.stagger].filter(Boolean)) {
      const needle = isCss ? cssVar(t) : `.${t.split(".").pop()}`;
      if (!code.includes(needle)) errors.push(`${where}: ${file} does not use ${needle}`);
    }
    const curveNeedle = beat.easing === "linear" ? "linear" : isCss ? cssVar(`motion.easing.${beat.easing}`) : `easing.${beat.easing}`;
    if (!code.includes(curveNeedle)) errors.push(`${where}: ${file} does not use ${curveNeedle}`);
  }
}

for (const name of core.keys()) {
  const componentToken = /^motion\.(?!duration\.|easing\.)/.test(name);
  if (componentToken && !used.has(name)) errors.push(`token "${name}" is not documented in tokens/motion-usage.json`);
}

if (errors.length) {
  console.error(`Motion spec check failed:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}

const delayMs = (beat) => beat.delay.reduce((t, [token, factor]) => t + ms(token) * factor, 0);
const delayText = (beat) =>
  beat.delay.length ? beat.delay.map(([token, factor]) => (factor === 1 ? `\`${token}\`` : `\`${token}\` × ${factor}`)).join(" + ") : "none";

const lines = [
  "# Motion spec",
  "",
  "Generated by `scripts/build-motion-spec.mjs` from `tokens/core.json` and `tokens/motion-usage.json`. Do not edit by hand.",
  "",
  "Brands cannot override any value on this page: timing and feel are the same in every brand.",
  "With `prefers-reduced-motion: reduce` every animation and transition below is switched off and each element shows its end state at once.",
  "",
  "## Durations",
  "",
  "| Token | Value |",
  "|---|---|",
  ...[...core].filter(([n]) => n.startsWith("motion.duration.")).map(([n, t]) => `| \`${n}\` | ${t.$value} |`),
  "",
  "## Curves",
  "",
  "| Token | CSS |",
  "|---|---|",
  ...[...core].filter(([n]) => n.startsWith("motion.easing.")).map(([n]) => `| \`${n}\` | \`${curve(n.split(".").pop())}\` |`),
];

for (const component of usage.components) {
  lines.push("", `## ${component.name}`, "", `Trigger: ${component.trigger}. Source: \`${component.file}\`.`, "");
  lines.push("| Beat | What happens | Property | Starts at | Duration | Curve | Duration token | Start is the sum of |", "|---|---|---|---|---|---|---|---|");
  for (const beat of component.beats) {
    const stagger = beat.stagger ? `, then +${ms(beat.stagger)} ms per item (\`${beat.stagger}\`)` : "";
    lines.push(
      `| ${beat.beat} | ${beat.what} | ${beat.property} | ${Math.round(delayMs(beat))} ms${stagger} | ${ms(beat.duration)} ms | ${beat.easing} \`${curve(beat.easing)}\` | \`${beat.duration}\` | ${delayText(beat)} |`,
    );
  }
}

writeFileSync(join(root, "docs/MOTION.md"), lines.join("\n") + "\n");
const beats = usage.components.reduce((n, c) => n + c.beats.length, 0);
console.log(`motion spec: ${usage.components.length} components, ${beats} beats, matches the code -> docs/MOTION.md`);
