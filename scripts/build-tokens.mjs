// Builds tokens/*.json (W3C design-token format) into:
//   src/styles/tokens.css      CSS custom properties, one block per brand
//   src/tokens/generated.ts    the same motion values for JavaScript
// It also enforces the brand contract, so a new brand cannot ship half-finished.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { flatten, resolve } from "./lib/tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const cssValue = (t) => (t.$type === "cubicBezier" ? `cubic-bezier(${t.$value.join(", ")})` : t.$value);
const cssBlock = (selector, tokens) =>
  `${selector} {\n${[...tokens].map(([n, t]) => `  --rk-${n.replaceAll(".", "-")}: ${cssValue(t)};`).join("\n")}\n}\n`;

// WCAG 2 contrast ratio
function contrast(a, b) {
  const lum = (hex) => {
    const [r, g, bl] = [1, 3, 5]
      .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
      .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
  };
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

// [foreground, background, minimum ratio]
const CONTRAST_RULES = [
  ["color.text", "color.bg", 4.5],
  ["color.text", "color.surface", 4.5],
  ["color.text-muted", "color.bg", 4.5],
  ["color.text-muted", "color.surface", 4.5],
  ["color.on-accent", "color.accent", 4.5],
  ["color.tier-mini", "color.surface", 3],
  ["color.tier-minor", "color.surface", 3],
  ["color.tier-major", "color.surface", 4.5], // also used for small bonus text
  ["color.tier-grand", "color.surface", 3],
];

const core = resolve(flatten(read("tokens/core.json")));
const brandFiles = readdirSync(join(root, "tokens/brands")).filter((f) => f.endsWith(".json")).sort();
const brands = brandFiles
  .map((file) => {
    const json = read(`tokens/brands/${file}`);
    return {
      id: file.replace(".json", ""),
      name: json.$name,
      order: json.$order ?? 99,
      description: json.$description,
      tokens: resolve(flatten(json)),
    };
  })
  .sort((a, b) => a.order - b.order);

const errors = [];
const contract = [...brands[0].tokens.keys()].sort();
for (const brand of brands) {
  const keys = [...brand.tokens.keys()].sort();
  for (const k of contract) if (!keys.includes(k)) errors.push(`${brand.id}: missing token "${k}"`);
  for (const k of keys) {
    if (!contract.includes(k)) errors.push(`${brand.id}: extra token "${k}" (not in ${brands[0].id})`);
    if (core.has(k)) errors.push(`${brand.id}: "${k}" is a core token and cannot be overridden`);
  }
  for (const [fg, bg, min] of CONTRAST_RULES) {
    if (!brand.tokens.has(fg) || !brand.tokens.has(bg)) continue;
    const ratio = contrast(brand.tokens.get(fg).$value, brand.tokens.get(bg).$value);
    if (ratio < min) errors.push(`${brand.id}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`);
  }
}
if (errors.length) {
  console.error(`Token check failed:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}

// The generated files are not in git, so on a fresh clone their folders may not exist yet.
mkdirSync(join(root, "src/styles"), { recursive: true });
mkdirSync(join(root, "src/tokens"), { recursive: true });

const banner = "/* Generated by scripts/build-tokens.mjs. Edit tokens/*.json instead. */\n";
writeFileSync(
  join(root, "src/styles/tokens.css"),
  banner + cssBlock(":root", core) + brands.map((b) => cssBlock(`[data-brand="${b.id}"]`, b.tokens)).join(""),
);

const group = (prefix, map) =>
  Object.fromEntries([...core].filter(([n]) => n.startsWith(prefix)).map(([n, t]) => [n.slice(prefix.length), map(t.$value)]));
const ms = (v) => parseFloat(v);
const ts = `${banner}
export const duration = ${JSON.stringify(group("motion.duration.", ms), null, 2)} as const;

export const easing = ${JSON.stringify(group("motion.easing.", (v) => v), null, 2)} as const;

export const chest = ${JSON.stringify(group("motion.chest.", ms), null, 2)} as const;

export const level = ${JSON.stringify(group("motion.level.", ms), null, 2)} as const;

export const streak = ${JSON.stringify(group("motion.streak.", ms), null, 2)} as const;

/** Every motion duration token by its full name, in milliseconds. */
export const motionMs: Record<string, number> = ${JSON.stringify(
  Object.fromEntries([...core].filter(([, t]) => t.$type === "duration").map(([n, t]) => [n, ms(t.$value)])),
  null,
  2,
)};

export const brands = ${JSON.stringify(brands.map(({ id, name, description }) => ({ id, name, description })), null, 2)} as const;

export type BrandId = (typeof brands)[number]["id"];
`;
writeFileSync(join(root, "src/tokens/generated.ts"), ts);

console.log(
  `tokens: ${core.size} core, ${brands.length} brands x ${contract.length} (${brands.map((b) => b.id).join(", ")}), contract and contrast OK`,
);
