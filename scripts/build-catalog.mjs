// Writes docs/PRIMITIVES.md: the one page an agent (or a new designer) reads
// before composing a template. It is generated from the @primitive and
// @helper comment blocks and the Props types in the source, so it cannot
// describe a prop that does not exist.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const list = (dir, test) => readdirSync(join(root, dir)).filter(test).sort().map((f) => `${dir}/${f}`);

// "/* @primitive\nname: X\nuse: ...\n*/"  ->  { name, use, not, rules, example: [] }
function block(source, tag) {
  const match = source.match(new RegExp(`/\\* @${tag}\\n([\\s\\S]*?)\\*/`));
  if (!match) return null;
  const out = { example: [] };
  for (const line of match[1].split("\n")) {
    const field = line.match(/^(\w+):\s*(.*)$/);
    if (!field) continue;
    if (field[1] === "example") out.example.push(field[2]);
    else out[field[1]] = field[2];
  }
  return out;
}

const propsOf = (source) => source.match(/type Props = \{\n([\s\S]*?)\n\};/)?.[1] ?? null;

const errors = [];
const primitives = [];
for (const file of list("src/components", (f) => f.endsWith(".tsx"))) {
  const source = read(file);
  const info = block(source, "primitive");
  const props = propsOf(source);
  if (!info) errors.push(`${file}: no @primitive block`);
  else if (!info.name || !info.use || !info.not || !info.rules || !info.example.length)
    errors.push(`${file}: @primitive needs name, use, not, rules and at least one example`);
  if (!props) errors.push(`${file}: no "type Props = { ... };" to document`);
  if (info && props) primitives.push({ file, props, ...info });
}

const helpers = [];
for (const file of list("src/lib", (f) => /\.ts$/.test(f) && !f.endsWith(".test.ts"))) {
  const info = block(read(file), "helper");
  if (info) helpers.push({ file, ...info });
}

if (errors.length) {
  console.error(`Catalogue check failed:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}

const lines = [
  "# Primitives",
  "",
  "Generated by `scripts/build-catalog.mjs` from the source. Do not edit by hand.",
  "",
  "A template is a screen made only of these primitives, plus the rule that connects them.",
  "If a brief needs something that is not here, that is a gap to report, not something to build inside a template.",
  "",
  "| Primitive | Use it for | Not for |",
  "|---|---|---|",
  ...primitives.map((p) => `| [${p.name}](#${p.name.toLowerCase()}) | ${p.use} | ${p.not} |`),
];

for (const p of primitives) {
  lines.push(
    "", `## ${p.name}`, "", `Source: \`${p.file}\``, "",
    `**Use it for:** ${p.use}`, "", `**Not for:** ${p.not}`, "", `**Rules:** ${p.rules}`, "",
    "```tsx", ...p.example, "```", "", "Props:", "", "```ts", p.props, "```",
  );
}

lines.push("", "# Helpers", "", "Data and logic a template may import from `src/lib`.");
for (const h of helpers) {
  lines.push("", `## ${h.name}`, "", `Source: \`${h.file}\``, "", h.use);
  if (h.rules) lines.push("", `**Rules:** ${h.rules}`);
}

writeFileSync(join(root, "docs/PRIMITIVES.md"), lines.join("\n") + "\n");
console.log(`catalogue: ${primitives.length} primitives, ${helpers.length} helpers -> docs/PRIMITIVES.md`);
