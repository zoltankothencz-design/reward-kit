// Writes figma/variables.js: a Figma Plugin API script that creates or updates
// the Reward Kit variables from tokens/*.json. The code is the source of
// truth; Figma is generated from it, never edited by hand.
//   npm run figma
// Run the generated script in the Figma file (through the Figma MCP tool
// `use_figma`, or pasted into a plugin). It is safe to run again: variables
// are matched by name and updated in place.
//
// Layout in Figma:
//   collection "Brand"  one mode per brand (Aurum, Amber, Frost): colours, radii, font families
//   collection "Core"   one mode: spacing, font sizes, motion durations and curves
// Figma plans that allow only one mode per collection get one collection per
// brand instead ("Brand / Aurum", ...); the script detects that and says so.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { flatten, resolve } from "./lib/tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

// One token -> [name, kind, value]. Kinds: c colour (hex), n number, f font family, s text.
function row(token, t) {
  if (t.$type === "color") return [token, "c", t.$value];
  if (t.$type === "fontFamily") return [token, "f", t.$value.match(/'([^']+)'/)[1]];
  if (t.$type === "cubicBezier") return [token, "s", `cubic-bezier(${t.$value.join(", ")})`];
  if (/^-?[\d.]+(px|ms)$/.test(t.$value)) return [token, "n", parseFloat(t.$value)];
  return [token, "s", t.$value]; // em values: Figma number variables have no em unit
}
const rows = (json) => [...resolve(flatten(json))].map(([token, t]) => row(token, t));

const core = rows(read("tokens/core.json"));
const brands = readdirSync(join(root, "tokens/brands"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => read(`tokens/brands/${f}`))
  .sort((a, b) => (a.$order ?? 99) - (b.$order ?? 99))
  .map((json) => [json.$name, rows(json)]);

const script = `// Generated by scripts/build-figma.mjs from tokens/*.json. Do not edit by hand.
// Rows are [token, kind, value]; kinds: c colour, n number, f font family, s text.
const CORE = ${JSON.stringify(core)};
const BRANDS = ${JSON.stringify(brands)};

// Which Figma pickers offer each variable. Never ALL_SCOPES.
function scopes(token, kind) {
  if (kind === "f") return ["FONT_FAMILY"];
  if (token.startsWith("radius.")) return ["CORNER_RADIUS"];
  if (token.startsWith("space.")) return ["GAP", "WIDTH_HEIGHT"];
  if (token.startsWith("font-size.")) return ["FONT_SIZE"];
  if (token.startsWith("motion.") || token.startsWith("font.")) return []; // documented values, not pickable
  if (/^color\\.(text|text-muted|on-accent)$/.test(token)) return ["TEXT_FILL"];
  if (token === "color.border") return ["STROKE_COLOR"];
  if (token.startsWith("color.tier-")) return ["FRAME_FILL", "SHAPE_FILL", "TEXT_FILL", "STROKE_COLOR"];
  return ["FRAME_FILL", "SHAPE_FILL"];
}
const TYPE = { c: "COLOR", n: "FLOAT", f: "STRING", s: "STRING" };
const hex = (h) => ({ r: parseInt(h.slice(1, 3), 16) / 255, g: parseInt(h.slice(3, 5), 16) / 255, b: parseInt(h.slice(5, 7), 16) / 255 });

// A font-family variable can only be set once its font is loaded.
const available = await figma.listAvailableFontsAsync();
const missingFonts = [];
for (const family of new Set(BRANDS.flatMap(([, vars]) => vars.filter((v) => v[1] === "f").map((v) => v[2])))) {
  const styles = available.filter((f) => f.fontName.family === family);
  if (!styles.length) missingFonts.push(family);
  for (const f of styles) await figma.loadFontAsync(f.fontName);
}

const collections = await figma.variables.getLocalVariableCollectionsAsync();
const allVars = await figma.variables.getLocalVariablesAsync();
const find = (name) => collections.find((c) => c.name === name);
const collection = (name) => find(name) ?? (collections.push(figma.variables.createVariableCollection(name)), find(name));
let created = 0, updated = 0;

function write(coll, modeId, [token, kind, value]) {
  const name = token.replaceAll(".", "/");
  let variable = allVars.find((x) => x.name === name && x.variableCollectionId === coll.id);
  if (variable) updated++;
  else {
    variable = figma.variables.createVariable(name, coll, TYPE[kind]);
    allVars.push(variable);
    created++;
  }
  variable.scopes = scopes(token, kind);
  variable.setVariableCodeSyntax("WEB", "var(--rk-" + token.replaceAll(".", "-") + ")");
  variable.description = "Token " + token;
  variable.setValueForMode(modeId, kind === "c" ? hex(value) : value);
}

const coreColl = collection("Core");
coreColl.renameMode(coreColl.modes[0].modeId, "Value");
for (const v of CORE) write(coreColl, coreColl.modes[0].modeId, v);

// Brand: one mode per brand if the plan allows it, else one collection per brand.
const perBrand = (name) => "Brand / " + name;
let layout = find(perBrand(BRANDS[0][0])) ? "collections" : "modes";
let reason = "";
if (layout === "modes") {
  const brandColl = collection("Brand");
  brandColl.renameMode(brandColl.modes[0].modeId, BRANDS[0][0]);
  try {
    for (const [name] of BRANDS.slice(1)) if (!brandColl.modes.some((m) => m.name === name)) brandColl.addMode(name);
    for (const [name, vars] of BRANDS) {
      const modeId = brandColl.modes.find((m) => m.name === name).modeId;
      for (const v of vars) write(brandColl, modeId, v);
    }
  } catch (error) {
    layout = "collections";
    reason = String(error.message || error);
    brandColl.name = perBrand(BRANDS[0][0]); // reuse it for the first brand
  }
}
if (layout === "collections") {
  for (const [name, vars] of BRANDS) {
    const coll = collection(perBrand(name));
    coll.renameMode(coll.modes[0].modeId, "Value");
    for (const v of vars) write(coll, coll.modes[0].modeId, v);
  }
}

return {
  layout, reason, missingFonts, created, updated,
  collections: collections.map((c) => ({ name: c.name, id: c.id, modes: c.modes.map((m) => m.name), variables: c.variableIds.length })),
};
`;

mkdirSync(join(root, "figma"), { recursive: true });
writeFileSync(join(root, "figma/variables.js"), script);
console.log(`figma: ${core.length} core + ${brands.length} x ${brands[0][1].length} brand variables -> figma/variables.js (${script.length} characters)`);
